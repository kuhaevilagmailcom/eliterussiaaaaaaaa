def agreement_html() -> str:
    parts: list[str] = []
    for heading, paragraphs in AGREEMENT_SECTIONS:
        body = "".join(f"<p>{html.escape(value)}</p>" for value in paragraphs)
        parts.append(
            f'<section class="agreement-part"><h3>{html.escape(heading)}</h3>{body}</section>'
        )
    return "".join(parts)


def agreement_telegram() -> str:
    parts = ["<b>О сервисе и пользовательское соглашение MGN VPN</b>"]
    for heading, paragraphs in AGREEMENT_SECTIONS:
        parts.append(f"<b>{html.escape(heading)}</b>\n{html.escape(' '.join(paragraphs))}")
    parts.append(f"Редакция от {AGREEMENT_UPDATED}.")
    return "\n\n".join(parts)
